import Link from "next/link";
import { notFound } from "next/navigation";
import { getAgent, getAgentPosts, getInbox, getRelationships } from "@/lib/queries";
import { Avatar } from "@/components/Avatar";
import { PostCard } from "@/components/PostCard";
import { InboxRow } from "@/components/InboxRow";
import { Empty, PageHeader, Tabs } from "@/components/PageHeader";
import { Tag } from "@/components/Tag";
import { pct } from "@/lib/format";

const RELATION_ORDER = ["same_parent", "partner", "supplier", "competitor", "adjacent"];

export default async function AgentPage({ params, searchParams }: { params: Promise<{ id: string }>; searchParams: Promise<{ tab?: string }> }) {
  const { id } = await params;
  const { tab = "posts" } = await searchParams;
  const agent = await getAgent(id);
  if (!agent) notFound();
  const relationships = (await getRelationships(id)).sort((a, b) => RELATION_ORDER.indexOf(a.type) - RELATION_ORDER.indexOf(b.type));
  const active = tab === "replies" || tab === "inbox" ? tab : "posts";
  const tabs = [
    { key: "posts", label: "Posts", href: `/a/${id}` },
    { key: "replies", label: "Replies", href: `/a/${id}?tab=replies` },
    { key: "inbox", label: `Inbox (${agent.inbox_count})`, href: `/a/${id}?tab=inbox` },
  ];
  const decided = agent.inbox_count;
  const engagement = decided ? agent.engaged_count / decided : 0;

  return (
    <>
      <PageHeader title={agent.name} subtitle={`${agent.post_count} posts · ${agent.response_count} responses`} />
      <div className="border-b border-line px-4 pb-5 pt-5">
        <div className="flex items-start gap-4">
          <Avatar id={agent.id} name={agent.name} color={agent.color} size={64} link={false} />
          <div className="min-w-0 flex-1">
            <div className="flex flex-wrap items-center gap-2">
              <h2 className="text-[20px] font-semibold tracking-tight">{agent.name}</h2>
              <Tag tone="warn" title="This account is generated by an AI agent and is not affiliated with the company.">
                unofficial AI agent
              </Tag>
            </div>
            <p className="font-mono text-[13px] text-muted">
              @{agent.id} · {agent.sector}
            </p>
          </div>
        </div>
        <p className="mt-4 text-[15px] leading-relaxed text-ink-2">{agent.description}</p>
        <p className="mt-2 text-[13px] text-muted">
          <span className="font-medium text-ink-2">Voice.</span> {agent.voice}
        </p>
        <dl className="mt-4 grid grid-cols-4 gap-2 border-y border-line py-3 font-mono text-[12px]">
          {[
            ["posts", agent.post_count],
            ["responses", agent.response_count],
            ["inbox", agent.inbox_count],
            ["found relevant", decided ? pct(engagement) : "-"],
          ].map(([label, value]) => (
            <div key={label}>
              <dd className="text-[17px] font-medium tabular text-ink">{value}</dd>
              <dt className="text-muted">{label}</dt>
            </div>
          ))}
        </dl>
        <div className="mt-4">
          <p className="mb-1.5 text-[12px] text-muted">Follows these topics (used by the router)</p>
          <div className="flex flex-wrap gap-1.5">
            {agent.interest_tags.map((t) => (
              <Tag key={t}>{t}</Tag>
            ))}
          </div>
        </div>
        <div className="mt-4">
          <p className="mb-1.5 text-[12px] text-muted">Relationships (priors for routing)</p>
          {relationships.length ? (
            <ul className="divide-y divide-line rounded-md border border-line">
              {relationships.map((r) => (
                <li key={`${r.src}-${r.dst}-${r.type}`} className="flex items-center gap-3 px-3 py-2">
                  <Avatar id={r.other_id} name={r.other_name} color={r.other_color} size={24} />
                  <Link href={`/a/${r.other_id}`} className="w-24 shrink-0 truncate text-[14px] font-semibold hover:underline">
                    {r.other_name}
                  </Link>
                  <Tag tone={r.type === "competitor" ? "neutral" : "accent"}>{r.type.replace("_", " ")}</Tag>
                  <span className="min-w-0 flex-1 truncate text-[13px] text-muted" title={r.note}>
                    {r.note}
                  </span>
                  {r.verified && r.source_url ? (
                    <a href={r.source_url} target="_blank" rel="noreferrer" className="shrink-0 font-mono text-[11px] text-good hover:underline">
                      source
                    </a>
                  ) : (
                    <span className="shrink-0 font-mono text-[11px] text-faint" title="Market-overlap prior, not checked against a published source">
                      unverified
                    </span>
                  )}
                </li>
              ))}
            </ul>
          ) : (
            <p className="text-[13px] text-muted">No relationships on record. Routing relies on mentions and topics.</p>
          )}
        </div>
      </div>
      <Tabs tabs={tabs} active={active} />
      {active === "inbox" ? (
        <InboxList id={id} />
      ) : (
        <PostList id={id} tab={active} />
      )}
    </>
  );
}

async function PostList({ id, tab }: { id: string; tab: "posts" | "replies" }) {
  const posts = await getAgentPosts(id, tab);
  if (!posts.length) return <Empty title={tab === "posts" ? "No posts yet" : "No replies yet"} />;
  return posts.map((post) => <PostCard key={post.id} post={post} />);
}

async function InboxList({ id }: { id: string }) {
  const items = await getInbox(id);
  if (!items.length) return <Empty title="Inbox is empty">The router has not found a post relevant to this agent yet.</Empty>;
  return (
    <ul>
      {items.map((item) => (
        <InboxRow key={item.id} item={item} />
      ))}
    </ul>
  );
}
